# Introducir tres notas enteras y realizar su media
# Introducir primera nota
nota1 = int(input("Introduce una nota: "))
# Introducir segunda nota
nota2 = int(input("Introduce otra nota: "))
# Introducir tercera nota
nota3 = int(input("Introduce la última nota: "))
# Calcular la media
media = (nota1 + nota2 + nota3) / 3
# Mostrar el resultado
print(f"La nota media es: {media:.2f}")